//! Local GGUF model catalogue and resource-fit checks.
//!
//! This module validates the platform-neutral model catalogue, resolves safe
//! model paths, and verifies file integrity. Platform adapters own inference.

use serde::{Deserialize, Serialize};
use std::collections::HashSet;
use std::fmt;
use sha2::{Digest, Sha256};
use std::fs::{self, File};
use std::io::{BufReader, Read};
use std::path::{Component, Path, PathBuf};

pub const MODEL_CATALOG_SCHEMA_VERSION: u32 = 1;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ModelCatalog {
    pub schema_version: u32,
    #[serde(default)]
    pub models: Vec<LocalModelEntry>,
}

impl Default for ModelCatalog {
    fn default() -> Self {
        Self {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: Vec::new(),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct LocalModelEntry {
    /// Stable ID generated by Leo; not derived from a user-controlled path.
    pub id: String,
    pub display_name: String,
    /// Path relative to Leo's private model directory, e.g. `models/leo.gguf`.
    pub relative_path: String,
    pub format: String,
    pub file_size_bytes: u64,
    pub sha256: Option<String>,
    pub architecture: Option<String>,
    pub quantization: Option<String>,
    pub context_length: u32,
    /// Filled by native GGUF inspection when a reliable estimate is available.
    pub min_required_ram_bytes: Option<u64>,
    /// Empty means the model has not been restricted to a platform.
    #[serde(default)]
    pub supported_platforms: Vec<String>,
    pub imported_at_utc: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModelFit {
    Ready,
    NeedsInspection,
    UnsupportedPlatform,
    InsufficientMemory,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DeviceResources {
    pub platform: String,
    pub available_memory_bytes: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ModelCatalogError {
    UnsupportedSchemaVersion(u32),
    InvalidId(String),
    DuplicateId(String),
    EmptyDisplayName(String),
    UnsupportedFormat(String),
    UnsafeRelativePath(String),
    InvalidModelFileName(String),
    EmptyFile(String),
    FileSizeMismatch { path: String, expected: u64, actual: u64 },
    ChecksumMismatch { path: String, expected: String, actual: String },
    InvalidContextLength(String),
    InvalidSha256(String),
    ModelFileMissing(String),
    ModelPathOutsideRoot(String),
    Io(String),
    InvalidJson(String),
    InvalidGguf(String),
    ModelAlreadyExists(String),
    Storage(String),
}

impl fmt::Display for ModelCatalogError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedSchemaVersion(version) => {
                write!(formatter, "unsupported model catalogue schema: {version}")
            }
            Self::InvalidId(id) => write!(formatter, "invalid model id: {id}"),
            Self::DuplicateId(id) => write!(formatter, "duplicate model id: {id}"),
            Self::EmptyDisplayName(id) => write!(formatter, "model {id} has an empty display name"),
            Self::UnsupportedFormat(format) => {
                write!(formatter, "unsupported model format: {format}")
            }
            Self::UnsafeRelativePath(path) => write!(formatter, "unsafe model path: {path}"),
            Self::InvalidModelFileName(path) => {
                write!(formatter, "model file must be a .gguf file: {path}")
            }
            Self::EmptyFile(id) => write!(formatter, "model file size is zero: {id}"),
            Self::FileSizeMismatch { path, expected, actual } => write!(
                formatter,
                "model file size mismatch for {path}: expected {expected}, found {actual}"
            ),
            Self::ChecksumMismatch { path, expected, actual } => write!(
                formatter,
                "model checksum mismatch for {path}: expected {expected}, found {actual}"
            ),
            Self::InvalidContextLength(id) => write!(formatter, "invalid context length: {id}"),
            Self::InvalidSha256(id) => write!(formatter, "invalid SHA-256 checksum: {id}"),
            Self::ModelFileMissing(path) => write!(formatter, "model file does not exist: {path}"),
            Self::ModelPathOutsideRoot(path) => {
                write!(formatter, "model path escapes the model directory: {path}")
            }
            Self::Io(message) => write!(formatter, "model catalogue I/O error: {message}"),
            Self::InvalidJson(message) => {
                write!(formatter, "invalid model catalogue JSON: {message}")
            }
            Self::InvalidGguf(message) => write!(formatter, "invalid GGUF model: {message}"),
            Self::ModelAlreadyExists(id) => write!(formatter, "model already exists: {id}"),
            Self::Storage(message) => write!(formatter, "model library storage error: {message}"),
        }
    }
}

impl std::error::Error for ModelCatalogError {}

impl ModelCatalog {
    pub fn from_json(json: &str) -> Result<Self, ModelCatalogError> {
        let catalogue: Self = serde_json::from_str(json)
            .map_err(|error| ModelCatalogError::InvalidJson(error.to_string()))?;
        catalogue.validate()?;
        Ok(catalogue)
    }

    pub fn to_json_pretty(&self) -> Result<String, ModelCatalogError> {
        self.validate()?;
        serde_json::to_string_pretty(self)
            .map_err(|error| ModelCatalogError::InvalidJson(error.to_string()))
    }

    pub fn validate(&self) -> Result<(), ModelCatalogError> {
        if self.schema_version != MODEL_CATALOG_SCHEMA_VERSION {
            return Err(ModelCatalogError::UnsupportedSchemaVersion(self.schema_version));
        }

        let mut ids = HashSet::with_capacity(self.models.len());
        for model in &self.models {
            if !is_valid_model_id(&model.id) {
                return Err(ModelCatalogError::InvalidId(model.id.clone()));
            }
            if !ids.insert(model.id.as_str()) {
                return Err(ModelCatalogError::DuplicateId(model.id.clone()));
            }
            if model.display_name.trim().is_empty() {
                return Err(ModelCatalogError::EmptyDisplayName(model.id.clone()));
            }
            if !model.format.eq_ignore_ascii_case("gguf") {
                return Err(ModelCatalogError::UnsupportedFormat(model.format.clone()));
            }
            validate_relative_model_path(&model.relative_path)?;
            if !model.relative_path.to_ascii_lowercase().ends_with(".gguf") {
                return Err(ModelCatalogError::InvalidModelFileName(model.relative_path.clone()));
            }
            if model.file_size_bytes == 0 {
                return Err(ModelCatalogError::EmptyFile(model.id.clone()));
            }
            if model.context_length == 0 {
                return Err(ModelCatalogError::InvalidContextLength(model.id.clone()));
            }
            if let Some(checksum) = &model.sha256 {
                if checksum.len() != 64 || !checksum.bytes().all(|byte| byte.is_ascii_hexdigit()) {
                    return Err(ModelCatalogError::InvalidSha256(model.id.clone()));
                }
            }
        }
        Ok(())
    }

    /// Resolves a catalogue entry without allowing absolute paths, `..`, or
    /// symlinks to escape the app-private model directory.
    pub fn resolve_model_path(
        &self,
        model_id: &str,
        model_root: &Path,
    ) -> Result<PathBuf, ModelCatalogError> {
        self.validate()?;
        let model = self
            .models
            .iter()
            .find(|model| model.id == model_id)
            .ok_or_else(|| ModelCatalogError::ModelFileMissing(model_id.to_owned()))?;
        validate_relative_model_path(&model.relative_path)?;

        let canonical_root = model_root
            .canonicalize()
            .map_err(|error| ModelCatalogError::Io(error.to_string()))?;
        let candidate = canonical_root.join(&model.relative_path);
        let canonical_candidate = candidate
            .canonicalize()
            .map_err(|_| ModelCatalogError::ModelFileMissing(model.relative_path.clone()))?;

        if !canonical_candidate.starts_with(&canonical_root) {
            return Err(ModelCatalogError::ModelPathOutsideRoot(model.relative_path.clone()));
        }
        if !canonical_candidate.is_file() {
            return Err(ModelCatalogError::ModelFileMissing(model.relative_path.clone()));
        }
        Ok(canonical_candidate)
    }

    pub fn assess_fit(&self, model_id: &str, device: &DeviceResources) -> Option<ModelFit> {
        let model = self.models.iter().find(|model| model.id == model_id)?;
        if !model.supported_platforms.is_empty()
            && !model
                .supported_platforms
                .iter()
                .any(|platform| platform.eq_ignore_ascii_case(&device.platform))
        {
            return Some(ModelFit::UnsupportedPlatform);
        }
        let Some(required_memory) = model.min_required_ram_bytes else {
            return Some(ModelFit::NeedsInspection);
        };
        Some(if required_memory <= device.available_memory_bytes {
            ModelFit::Ready
        } else {
            ModelFit::InsufficientMemory
        })
    }
}

pub(crate) fn is_valid_model_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 80
        && id.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-' || byte == b'_'
        })
}

fn validate_relative_model_path(path: &str) -> Result<(), ModelCatalogError> {
    let parsed = Path::new(path);
    if path.trim().is_empty()
        || path.contains('\\')
        || path.contains(':')
        || parsed.is_absolute()
        || parsed.components().any(|component| !matches!(component, Component::Normal(_)))
    {
        return Err(ModelCatalogError::UnsafeRelativePath(path.to_owned()));
    }
    Ok(())
}

/// Re-checks the actual file size so stale manifests cannot silently describe
/// a different file.
pub fn verify_file_size(path: &Path, expected_size: u64) -> Result<(), ModelCatalogError> {
    let metadata = fs::metadata(path)
        .map_err(|_| ModelCatalogError::ModelFileMissing(path.display().to_string()))?;
    if !metadata.is_file() || metadata.len() != expected_size {
        return Err(ModelCatalogError::FileSizeMismatch {
            path: path.display().to_string(),
            expected: expected_size,
            actual: metadata.len(),
        });
    }
    Ok(())
}

/// Calculates a streaming SHA-256 digest without loading the complete model
/// into memory. This is intentionally used before a multi-gigabyte GGUF file
/// is handed to the native loader.
pub fn sha256_file(path: &Path) -> Result<String, ModelCatalogError> {
    let file = File::open(path)
        .map_err(|error| ModelCatalogError::Io(error.to_string()))?;
    let mut reader = BufReader::with_capacity(1024 * 1024, file);
    let mut digest = Sha256::new();
    let mut buffer = [0_u8; 1024 * 1024];
    loop {
        let read = reader
            .read(&mut buffer)
            .map_err(|error| ModelCatalogError::Io(error.to_string()))?;
        if read == 0 {
            break;
        }
        digest.update(&buffer[..read]);
    }
    Ok(format!("{:x}", digest.finalize()))
}

/// Verifies both the recorded size and optional SHA-256 digest.
pub fn verify_file_integrity(
    path: &Path,
    expected_size: u64,
    expected_sha256: Option<&str>,
) -> Result<(), ModelCatalogError> {
    verify_file_size(path, expected_size)?;
    if let Some(expected) = expected_sha256 {
        let actual = sha256_file(path)?;
        if !actual.eq_ignore_ascii_case(expected) {
            return Err(ModelCatalogError::ChecksumMismatch {
                path: path.display().to_string(),
                expected: expected.to_ascii_lowercase(),
                actual,
            });
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::{SystemTime, UNIX_EPOCH};

    fn model(relative_path: &str) -> LocalModelEntry {
        LocalModelEntry {
            id: "small-instruct-q4".into(),
            display_name: "Small Instruct Q4".into(),
            relative_path: relative_path.into(),
            format: "GGUF".into(),
            file_size_bytes: 1024,
            sha256: Some("a".repeat(64)),
            architecture: Some("llama".into()),
            quantization: Some("Q4_K_M".into()),
            context_length: 4096,
            min_required_ram_bytes: Some(2 * 1024 * 1024 * 1024),
            supported_platforms: vec!["android-arm64".into(), "windows-x64".into()],
            imported_at_utc: "2026-11-15T00:00:00Z".into(),
        }
    }

    fn temporary_directory() -> PathBuf {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("clock must be after epoch")
            .as_nanos();
        let path = std::env::temp_dir().join(format!("leo-model-catalog-{stamp}"));
        fs::create_dir_all(&path).expect("temporary directory must be created");
        path
    }

    #[test]
    fn empty_catalogue_has_current_schema() {
        assert_eq!(ModelCatalog::default().schema_version, MODEL_CATALOG_SCHEMA_VERSION);
        assert!(ModelCatalog::default().models.is_empty());
    }

    #[test]
    fn valid_catalogue_round_trips_json() {
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![model("models/small.gguf")],
        };
        let json = catalogue.to_json_pretty().unwrap();
        assert_eq!(ModelCatalog::from_json(&json).unwrap(), catalogue);
    }

    #[test]
    fn path_traversal_is_rejected() {
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![model("../../private/model.gguf")],
        };
        assert!(matches!(catalogue.validate(), Err(ModelCatalogError::UnsafeRelativePath(_))));
    }

    #[test]
    fn absolute_model_paths_are_rejected() {
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![model("/tmp/model.gguf")],
        };
        assert!(matches!(catalogue.validate(), Err(ModelCatalogError::UnsafeRelativePath(_))));
    }

    #[test]
    fn duplicate_ids_are_rejected() {
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![model("models/one.gguf"), model("models/two.gguf")],
        };
        assert!(matches!(catalogue.validate(), Err(ModelCatalogError::DuplicateId(_))));
    }

    #[test]
    fn invalid_checksum_is_rejected() {
        let mut entry = model("models/small.gguf");
        entry.sha256 = Some("not-a-sha256".into());
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![entry],
        };
        assert!(matches!(catalogue.validate(), Err(ModelCatalogError::InvalidSha256(_))));
    }

    #[test]
    fn unknown_memory_requirement_is_not_reported_as_ready() {
        let mut entry = model("models/small.gguf");
        entry.min_required_ram_bytes = None;
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![entry],
        };
        let device = DeviceResources {
            platform: "android-arm64".into(),
            available_memory_bytes: u64::MAX,
        };
        assert_eq!(
            catalogue.assess_fit("small-instruct-q4", &device),
            Some(ModelFit::NeedsInspection)
        );
    }

    #[test]
    fn platform_and_memory_are_checked_before_recommending_a_model() {
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![model("models/small.gguf")],
        };
        let unsupported = DeviceResources {
            platform: "linux-x64".into(),
            available_memory_bytes: u64::MAX,
        };
        let low_memory = DeviceResources {
            platform: "android-arm64".into(),
            available_memory_bytes: 512 * 1024 * 1024,
        };
        let enough_memory = DeviceResources {
            platform: "windows-x64".into(),
            available_memory_bytes: 4 * 1024 * 1024 * 1024,
        };
        assert_eq!(
            catalogue.assess_fit("small-instruct-q4", &unsupported),
            Some(ModelFit::UnsupportedPlatform)
        );
        assert_eq!(
            catalogue.assess_fit("small-instruct-q4", &low_memory),
            Some(ModelFit::InsufficientMemory)
        );
        assert_eq!(
            catalogue.assess_fit("small-instruct-q4", &enough_memory),
            Some(ModelFit::Ready)
        );
    }

    #[test]
    fn sha256_is_calculated_and_verified_without_reading_the_whole_file() {
        let root = temporary_directory();
        let file = root.join("sample.gguf");
        fs::write(&file, b"abc").unwrap();
        let digest = sha256_file(&file).unwrap();
        assert_eq!(
            digest,
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
        assert!(verify_file_integrity(&file, 3, Some(&digest)).is_ok());
        assert!(matches!(
            verify_file_integrity(&file, 3, Some(&"0".repeat(64))),
            Err(ModelCatalogError::ChecksumMismatch { .. })
        ));
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn resolved_model_file_must_remain_inside_model_root() {
        let root = temporary_directory();
        let model_dir = root.join("models");
        fs::create_dir_all(&model_dir).unwrap();
        let model_file = model_dir.join("small.gguf");
        fs::write(&model_file, [1_u8, 2, 3]).unwrap();
        let catalogue = ModelCatalog {
            schema_version: MODEL_CATALOG_SCHEMA_VERSION,
            models: vec![LocalModelEntry { file_size_bytes: 3, ..model("models/small.gguf") }],
        };
        let resolved = catalogue.resolve_model_path("small-instruct-q4", &root).unwrap();
        assert_eq!(resolved, model_file.canonicalize().unwrap());
        fs::remove_dir_all(root).unwrap();
    }
}
