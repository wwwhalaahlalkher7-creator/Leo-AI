"""Exercise the bridge-generation shell workflow with hermetic tool shims.

The test does not pretend to run the FRB compiler. It verifies argument flow,
path interpretation, early checks, and required outputs without Flutter/Rust
SDKs on the unit-test host.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]


class GenerateBridgeBootstrapTests(unittest.TestCase):
    def test_script_uses_canonical_rust_fallback_and_verifies_all_bindings(self) -> None:
        with tempfile.TemporaryDirectory(prefix="leo-frb-test-") as temp:
            sandbox = Path(temp)
            repo = sandbox / "repo"
            app = repo / "apps" / "leo_app"
            bridge = repo / "core" / "bridge"
            fake_bin = sandbox / "bin"
            (app / "lib").mkdir(parents=True)
            (bridge / "src").mkdir(parents=True)
            fake_bin.mkdir()

            (repo / "scripts").mkdir(parents=True)
            shutil.copy2(ROOT / "scripts" / "generate_bridge.sh", repo / "scripts" / "generate_bridge.sh")
            shutil.copy2(ROOT / "apps" / "leo_app" / "flutter_rust_bridge.yaml", app / "flutter_rust_bridge.yaml")
            (bridge / "Cargo.toml").write_text(
                '[package]\nname="leo-bridge"\n\n'
                '[dependencies]\nflutter_rust_bridge = "=2.13.0"\n\n'
                '[lib]\ncrate-type = ["cdylib", "staticlib", "rlib"]\n',
                encoding="utf-8",
            )
            (bridge / "src" / "lib.rs").write_text("pub mod api;\n", encoding="utf-8")
            (app / "pubspec.yaml").write_text(
                "name: leo_app\n"
                "dependencies:\n"
                "  flutter_rust_bridge: 2.13.0\n"
                "  flutter_rust_bridge_hooks: 2.13.0\n"
                "dependency_overrides:\n"
                "  native_toolchain_rust: 1.1.1\n",
                encoding="utf-8",
            )
            (app / "hook").mkdir(parents=True)
            (app / "hook" / "build.dart").write_text(
                "FlutterRustBridgeNativeAssetsBuilder(\n"
                "  assetName: 'src/rust/frb_generated.io.dart',\n"
                "  cratePath: '../../core/bridge',\n"
                ");\n",
                encoding="utf-8",
            )
            toolchain_text = (
                '[toolchain]\nchannel = "1.100.0"\ntargets = ["aarch64-linux-android", "x86_64-unknown-linux-gnu"]\n'
            )
            (repo / "rust-toolchain.toml").write_text(toolchain_text, encoding="utf-8")
            (bridge / "rust-toolchain.toml").write_text(toolchain_text, encoding="utf-8")

            flutter = fake_bin / "flutter"
            flutter.write_text("#!/usr/bin/env bash\nexit 0\n", encoding="utf-8")
            cargo = fake_bin / "cargo"
            cargo.write_text(
                "#!/usr/bin/env bash\n"
                "if [[ \"$1 $2\" == \"expand --version\" ]]; then "
                "echo 'cargo-expand 1.0.126'; exit 0; fi\n"
                "echo \"unexpected cargo args: $*\" >&2; exit 9\n",
                encoding="utf-8",
            )
            dart = fake_bin / "dart"
            dart.write_text("#!/usr/bin/env bash\nexit 0\n", encoding="utf-8")
            codegen = fake_bin / "flutter_rust_bridge_codegen"
            codegen.write_text(
                "#!/usr/bin/env python3\n"
                "import pathlib, re, sys\n"
                "if sys.argv[1:] == ['--version']:\n"
                "    print('flutter_rust_bridge_codegen 2.13.0')\n"
                "    raise SystemExit(0)\n"
                "if sys.argv[1:] == ['generate', '--help']:\n"
                "    print('Usage: flutter_rust_bridge_codegen generate [OPTIONS]\\n  --skip-fvm-install')\n"
                "    raise SystemExit(0)\n"
                "assert sys.argv[1:] == ['generate', '--skip-fvm-install'], sys.argv\n"
                "app = pathlib.Path.cwd().resolve()\n"
                "config_file = app / 'flutter_rust_bridge.yaml'\n"
                "config = {}\n"
                "for line in config_file.read_text(encoding='utf-8').splitlines():\n"
                "    match = re.match(r'^([A-Za-z_][A-Za-z0-9_]*):\\s*(.*?)\\s*$', line)\n"
                "    if match: config[match.group(1)] = match.group(2).strip().strip(chr(34)).strip(chr(39))\n"
                "base_dir = config_file.parent.resolve()\n"
                "crate = (base_dir / config['rust_root']).resolve()\n"
                "# Mimic FRB 2.13 fallback_rust_output_path(canonical_rust_crate_dir).\n"
                "rust = crate / 'src/frb_generated.rs'\n"
                "assert not any(part == '..' for part in rust.parts), rust\n"
                "rust.parent.mkdir(parents=True, exist_ok=True)\n"
                "rust.write_text('// @generated by `flutter_rust_bridge`@ 2.13.0.\\n', encoding='utf-8')\n"
                "dart = (base_dir / config['dart_output']).resolve()\n"
                "dart.mkdir(parents=True, exist_ok=True)\n"
                "for name in ('frb_generated.dart', 'frb_generated.io.dart', 'frb_generated.web.dart'):\n"
                "    (dart / name).write_text('// generated\\n', encoding='utf-8')\n",
                encoding="utf-8",
            )
            for tool in (flutter, cargo, dart, codegen):
                tool.chmod(0o755)

            env = os.environ.copy()
            env["PATH"] = f"{fake_bin}{os.pathsep}{env.get('PATH', '')}"
            # Regression: a wrong crate root must be rejected before the
            # generator runs, so the default output cannot drift into the app.
            config_path = app / "flutter_rust_bridge.yaml"
            valid_config = config_path.read_text(encoding="utf-8")
            bad_config = valid_config.replace(
                "rust_root: ../../core/bridge",
                "rust_root: .",
            )
            self.assertNotEqual(valid_config, bad_config)
            config_path.write_text(bad_config, encoding="utf-8")
            result = subprocess.run(
                ["bash", str(repo / "scripts" / "generate_bridge.sh")],
                cwd=repo,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
            self.assertEqual(result.returncode, 1, msg=result.stdout + result.stderr)
            self.assertIn("invalid rust_root", result.stderr)
            self.assertIn("found '.'", result.stderr)
            self.assertFalse((app / "src" / "frb_generated.rs").exists())
            config_path.write_text(valid_config, encoding="utf-8")

            result = subprocess.run(
                ["bash", str(repo / "scripts" / "generate_bridge.sh")],
                cwd=repo,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )

            self.assertEqual(result.returncode, 0, msg=result.stdout + result.stderr)
            self.assertIn("FRB path contract passed", result.stdout)
            self.assertIn("Rust, common Dart, IO Dart and Web Dart bindings", result.stdout)
            self.assertTrue((bridge / "src/frb_generated.rs").is_file())
            self.assertTrue((app / "lib/src/rust/frb_generated.dart").is_file())
            self.assertTrue((app / "lib/src/rust/frb_generated.io.dart").is_file())
            self.assertTrue((app / "lib/src/rust/frb_generated.web.dart").is_file())
            self.assertFalse((app / "core/bridge").exists())

            # An executable with a mismatched CLI surface must be rejected
            # before the actual generator command is invoked. This models the
            # reported 2.13.0 failure where --skip-tool-install was not accepted.
            codegen.write_text(
                "#!/usr/bin/env python3\n"
                "import sys\n"
                "if sys.argv[1:] == ['--version']:\n"
                "    print('flutter_rust_bridge_codegen 2.13.0')\n"
                "elif sys.argv[1:] == ['generate', '--help']:\n"
                "    print('--skip-tool-install')\n"
                "else:\n"
                "    raise SystemExit('generator must not run with an unsupported CLI surface')\n",
                encoding="utf-8",
            )
            result = subprocess.run(
                ["bash", str(repo / "scripts" / "generate_bridge.sh")],
                cwd=repo,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
            self.assertEqual(result.returncode, 2, msg=result.stdout + result.stderr)
            self.assertIn("does not advertise --skip-fvm-install", result.stderr)
            self.assertIn("--skip-tool-install", result.stderr)

            # A stale generator earlier on PATH must be rejected before codegen.
            codegen.write_text(
                "#!/usr/bin/env python3\n"
                "print('flutter_rust_bridge_codegen 2.12.0')\n",
                encoding="utf-8",
            )
            result = subprocess.run(
                ["bash", str(repo / "scripts" / "generate_bridge.sh")],
                cwd=repo,
                env=env,
                text=True,
                capture_output=True,
                check=False,
            )
            self.assertEqual(result.returncode, 2, msg=result.stdout + result.stderr)
            self.assertIn("Expected flutter_rust_bridge_codegen 2.13.0", result.stderr)


if __name__ == "__main__":
    unittest.main()
